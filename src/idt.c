static struct idt_entry idt[IDT_NUM_ENTRIES];

/* CPU state pushed by the common interrupt handler */
struct cpu_state {
    unsigned int ebp;
    unsigned int edi;
    unsigned int esi;
    unsigned int edx;
    unsigned int ecx;
    unsigned int ebx;
    unsigned int eax;
} __attribute__((packed));

/* Stack state pushed by CPU on interrupt */
struct stack_state {
    unsigned int error_code;
    unsigned int eip;
    unsigned int cs;
    unsigned int eflags;
} __attribute__((packed));

/* Set a single IDT entry */
static void idt_set_entry(unsigned int index, unsigned int handler,
                          unsigned short sel, unsigned char type_attr)
{
    idt[index].offset_low  = handler & 0xFFFF;
    idt[index].offset_high = (handler >> 16) & 0xFFFF;
    idt[index].segment_sel = sel;
    idt[index].reserved    = 0;
    idt[index].type_attr   = type_attr;
}

/* Helper: build an array of handler addresses for easy iteration */
