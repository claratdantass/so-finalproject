/* IDT setup: creates interrupt gate entries and loads the table
 *
 * Each IDT entry is 64 bits describing an interrupt gate:
 *   - offset (handler address) split into low 16 and high 16 bits
 *   - segment selector (kernel code segment = 0x08)
 *   - type/attributes: present, DPL 0, 32-bit interrupt gate
 */

