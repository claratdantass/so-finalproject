#define IDT_NUM_ENTRIES 256
#define KERNEL_CODE_SEGMENT 0x08

/* IDT entry (interrupt gate descriptor) */
struct idt_entry {
    unsigned short offset_low;      /* lower 16 bits of handler address */
    unsigned short segment_sel;     /* kernel code segment selector */
    unsigned char  reserved;        /* always 0 */
    unsigned char  type_attr;       /* type and attributes (P, DPL, gate type) */
    unsigned short offset_high;     /* upper 16 bits of handler address */
} __attribute__((packed));

/* IDT pointer passed to lidt */
struct idt_ptr {
    unsigned short limit;           /* size of IDT - 1 */
    unsigned int   base;            /* address of first entry */
} __attribute__((packed));

