/* Despacho C (comum a todas as interrupções): dispositivos, EOI, preempção. */
void interrupt_handler(struct cpu_state cpu, unsigned int int_no,
                       struct stack_state stack)
{
    (void)cpu;

    if (int_no == 33) {
        keyboard_handler();
    }

    /* EOI antes de schedule (timer pode não retornar “logo”). */
    if (int_no >= 32 && int_no <= 47) {
        pic_acknowledge(int_no);
    }

    /* IRQ0 + CPL=3: tick do PIT → próximo processo pronto. */
    if (int_no == 32 && (stack.cs & 0x3) == 3) {
        schedule();
    }
}

/* Initialize IDT, remap PIC, enable interrupts */
void idt_init(void)
{
    /* zero out all entries first */
    unsigned int i;
    for (i = 0; i < IDT_NUM_ENTRIES; i++) {
        idt_set_entry(i, 0, 0, 0);
    }

    /* remap PIC so IRQs don't clash with CPU exceptions */
    pic_remap();

    /* install all handlers */
    idt_install_handlers();

    /* load the IDT */
    struct idt_ptr ptr;
    ptr.limit = sizeof(idt) - 1;
    ptr.base  = (unsigned int)&idt;
    load_idt(&ptr);

    /* enable interrupts */
    __asm__ __volatile__("sti");
}
